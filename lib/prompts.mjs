// 模式说明：照片模式要求忠于参考图；文字模式直接用用户描述的画面内容
export const PHOTO_RULE = `【参考图】按参考图中的主体来画：保留主体的数量、姿势、朝向和相对位置，以及毛色、发型、服装颜色等辨识特征；背影就画背影，不要凭空画出看不到的脸。如果风格要求里另有说明（例如只画其中某个主体），以风格要求为准。`;
export const MAX_SUBJECT = 500;

// 固定技术要求：为拼豆服务，像素风和扁平风都适用，始终附加在用户风格之后，页面只读展示
export const TECH_PROMPT = `【拼豆图纸固定要求，必须遵守】
这张图之后会被转换成拼豆（熔融豆）图纸，一个像素或色块对应一颗豆：
- 不要写实照片感。
- 色块干净：纯色填充，不要渐变、柔和阴影、噪点纹理、光效和模糊。
- 全图颜色不超过 16 种，相邻区域颜色区分明显。
- 主体和主要部位有清晰、连续的深色描边，浅色/白色部分也要描边。
- 去掉文字、水印、招牌和原图的背景场景。
- 纯白背景（#FFFFFF），没有地面、阴影和边框；主体居中、完整可见，约占画面 85%。`;
export const MAX_STYLE = 1000;

// 文字模式附加规则（不展示给用户）：画已有角色时必须一眼认得出
export const TEXT_RULE = '如果画面内容里有已有的动漫、卡通或游戏角色，要让人一眼认出：保留角色标志性的眼睛和五官、脸型、发型、服装和配色；下面的风格要求只改变画法（像素化、描边、配色数量），不要把角色的五官换成统一的模板。';

export function buildPrompt(job) {
  const head = job.mode === 'text' ? `【画面内容】\n${job.subject}\n\n${TEXT_RULE}` : PHOTO_RULE;
  return `${head}\n\n【风格要求】\n${job.style}\n\n${TECH_PROMPT}`;
}
